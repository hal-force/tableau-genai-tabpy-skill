#!/usr/bin/env python3
"""Regenerate docs/cli.md from each script's --help output.

  python3 tools/gen_cli_docs.py            # run from the repo root

Uses the current interpreter; runs every script with --help only (no
network, no credentials).
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = [
    ("scripts/genai_calc.py", "Generate the provider-specific SCRIPT_STR calculation."),
    ("scripts/set_secret.py", "Store / check / delete a secret without exposing it."),
    ("scripts/ca_bundle.py", "Export trusted roots to a CA bundle and probe TLS."),
    ("scripts/profile_data.py", "Profile a workbook or its data; detect risks; recommend a Payload."),
    ("scripts/compose_prompts.py", "Render a prompt spec into Prompts parameter members."),
    ("scripts/payload.py", "Build a Payload formula."),
    ("scripts/patch_workbook.py", "Write the patched .twb/.twbx."),
    ("scripts/server_io.py", "List / download / publish on Tableau Server or Cloud."),
    ("scripts/list_models.py", "List provider model ids for the Select LLM parameter."),
    ("tests/test_calc_e2e.py", "Every provider's calc against local mocks."),
    ("tests/test_workbook_calc.py", "The calc as it sits in a patched workbook."),
]


def main() -> int:
    out = ["# CLI reference", "",
           "Generated by `tools/gen_cli_docs.py` from each script's `--help`. "
           "Do not edit by hand.", "",
           "`scripts/keystore.py` is a library (no CLI); its lookup order is "
           "documented in [`reference/security.md`](../reference/security.md).", ""]
    for rel, blurb in SCRIPTS:
        r = subprocess.run([sys.executable, str(ROOT / rel), "--help"], capture_output=True, text=True,
                           cwd=ROOT, timeout=60)
        text = "\n".join(l for l in (r.stdout or r.stderr).splitlines()
                         if "RequestsDependencyWarning" not in l and "warnings.warn(" not in l)
        text = text.replace(str(Path.home()), "~")
        out += ["## `%s`" % rel, "", blurb, "", "```text", text.rstrip(), "```", ""]
    (ROOT / "docs" / "cli.md").write_text("\n".join(out))
    print("wrote docs/cli.md (%d scripts)" % len(SCRIPTS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
